"""Generate local Noto Sans KR subsets: python subset-font.py /path/to/NotoSansKR.ttf.

Requires the one-time build tools fonttools[woff], not a frontend dependency.
"""
import hashlib
import sys
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont


def ranges(codepoints):
    groups = []
    for value in sorted(codepoints):
        if groups and groups[-1][1] + 1 == value:
            groups[-1][1] = value
        else:
            groups.append([value, value])
    return ",".join(f"U+{a:X}" if a == b else f"U+{a:X}-{b:X}" for a, b in groups)


source = Path(sys.argv[1])
frontend = Path(__file__).resolve().parents[2]
output = frontend / "public" / "fonts"
original = TTFont(source)
characters = set(original.getBestCmap())
common = set()
for value in characters:
    # Keep Latin, symbols, Jamo and common Korean syllables in the preloaded font.
    if value < 0x2E80 or 0x3000 <= value <= 0x303F or 0x3130 <= value <= 0x318F or 0xFF00 <= value <= 0xFFEF:
        common.add(value)
    elif 0xAC00 <= value <= 0xD7A3:
        try:
            chr(value).encode("euc_kr")
        except UnicodeEncodeError:
            continue
        # Python also encodes uncommon syllables as eight-byte decompositions.
        if len(chr(value).encode("euc_kr")) == 2:
            common.add(value)

extended = characters - common
for name, codepoints in [("NotoSansKR-common.woff2", common), ("NotoSansKR-extended.woff2", extended)]:
    font = TTFont(source)
    options = subset.Options()
    options.layout_features = ["*"]
    processor = subset.Subsetter(options=options)
    processor.populate(unicodes=codepoints)
    processor.subset(font)
    font.flavor = "woff2"
    font.save(output / name)
    generated = TTFont(output / name)
    assert set(generated.getBestCmap()) == codepoints
    assert generated["fvar"].axes[0].minValue == 100
    assert generated["fvar"].axes[0].maxValue == 900
    print(name, (output / name).stat().st_size, "bytes", len(codepoints), "characters", flush=True)

assert common | extended == characters and not common & extended
(frontend / "src" / "styles" / "font-extended.css").write_text(
    "/* Generated by subset-font.py. Rare syllables and CJK load only when needed. */\n"
    "@font-face {\n"
    '  font-family: "Noto Sans KR Extended";\n'
    '  src: url("/fonts/NotoSansKR-extended.woff2") format("woff2");\n'
    "  font-style: normal;\n"
    "  font-weight: 100 900;\n"
    "  font-display: swap;\n"
    f"  unicode-range: {ranges(extended)};\n"
    "}\n", encoding="utf-8",
)
print("Source SHA-256:", hashlib.sha256(source.read_bytes()).hexdigest())
